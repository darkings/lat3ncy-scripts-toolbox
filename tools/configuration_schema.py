"""Explicit non-secret configuration fields for the native toolbox center.

Never derive editable fields from a user's TOML: credentials/unknown options stay
in their original file and never cross the settings JSON bridge.
"""
from __future__ import annotations


def field(key, label, default, *, choices=None, minimum=None, maximum=None, help='', readonly=False):
    kind = ('bool' if isinstance(default, bool) else 'int' if isinstance(default, int)
            else 'number' if isinstance(default, float) else 'list' if isinstance(default, list)
            else 'map' if isinstance(default, dict) else 'string')
    return dict(key=key, label=label, default=default, type=kind, choices=choices,
                minimum=minimum, maximum=maximum, help=help, readonly=readonly)


