# Fixed settings reload validation helpers. No commands are accepted from state.
Set-StrictMode -Version Latest
function Read-SettingsReloadJson {
    param([string]$Path)
    if ((Get-Item -LiteralPath $Path -ErrorAction Stop).Length -gt 8192) { throw 'reload-state-size' }
    return (Get-Content -LiteralPath $Path -Raw -Encoding UTF8 -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop)
}
function Assert-SettingsReloadRequest {
    param($Request, [string]$RequestId, [long]$Now)
    if ($RequestId -cnotmatch '^[0-9a-f]{32}$' -or $Request.id -isnot [string] -or $Request.id -cne $RequestId -or $Request.version -isnot [int] -or $Request.version -ne 1) { throw 'reload-id' }
    if ($Request.actions -isnot [string] -or $Request.owner_ticks -isnot [string] -or $Request.created_unix -isnot [long] -and $Request.created_unix -isnot [int]) { throw 'reload-type' }
    $actions = @(([string]$Request.actions).Split(','))
    if ($actions.Count -lt 1 -or $actions.Count -gt 3 -or @($actions | Select-Object -Unique).Count -ne $actions.Count) { throw 'reload-actions' }
    $allowed = @('version','id','actions','owner_pid','owner_ticks','created_unix')
    foreach ($action in $actions) {
        if ($action -cnotin @('power','theme','rgb')) { throw 'reload-action' }
        $key = $action + '_revision'; $allowed += $key
        if ($Request.$key -cnotmatch '^[0-9a-f]{64}$') { throw 'reload-revision' }
    }
    foreach ($property in $Request.PSObject.Properties.Name) { if ($property -cnotin $allowed) { throw 'reload-field' } }
    if ($Request.owner_pid -isnot [int] -or $Request.owner_pid -le 0 -or $Request.owner_ticks -cnotmatch '^[0-9]{10,20}$') { throw 'reload-owner' }
    $age = $Now - [long]$Request.created_unix
    if ($age -lt -5 -or $age -gt 120) { throw 'reload-stale' }
    return $actions
}
function Assert-SettingsReloadOwner {
    param($Request, [string]$Repo)
    $owner = Get-Process -Id $Request.owner_pid -ErrorAction Stop
    try {
        $expected = [IO.Path]::GetFullPath((Join-Path $Repo 'tools\ime-hud-winui\out\ImeHudWinUi.exe'))
        if ($owner.Path -ine $expected -or $owner.StartTime.ToUniversalTime().ToFileTimeUtc().ToString() -cne $Request.owner_ticks) { throw 'reload-owner-mismatch' }
        if (-not ('ToolboxReloadOwner' -as [type])) {
            Add-Type -TypeDefinition 'using System; using System.Runtime.InteropServices; public static class ToolboxReloadOwner { [DllImport("user32.dll",CharSet=CharSet.Unicode)] public static extern IntPtr FindWindow(string c,string t); [DllImport("user32.dll")] public static extern uint GetWindowThreadProcessId(IntPtr w,out uint p); }'
        }
        # HUD title reflects its current payload; its registered class is stable.
        $window = [ToolboxReloadOwner]::FindWindow('Lat3ncyImeHudWinUi',[NullString]::Value); [uint32]$windowOwner = 0
        if ($window -eq [IntPtr]::Zero) { throw 'reload-hud-missing' }
        [void][ToolboxReloadOwner]::GetWindowThreadProcessId($window,[ref]$windowOwner)
        if ($windowOwner -ne $Request.owner_pid) { throw 'reload-hud-owner' }
    } finally { $owner.Dispose() }
}
function Assert-SettingsTaskOwner {
    param($Task, [string]$Script)
    if ($null -eq $Task -or $Task.TaskPath -ne '\' -or @($Task.Actions).Count -ne 1) { throw 'reload-task-owner' }
    $action = $Task.Actions[0]
    $expected = '"' + [IO.Path]::GetFullPath($Script) + '"'
    if ([IO.Path]::GetFileName($action.Execute) -ieq 'wscript.exe') {
        $shim = ([string]$action.Arguments).Trim('"')
        if ($shim -notmatch '\.vbs$' -or -not [IO.Path]::IsPathRooted($shim)) { throw 'reload-shim' }
        $text = [IO.File]::ReadAllText($shim)
        if ($text -notlike '*Lat3ncy Toolbox - generated by Get-ThemeHiddenAction*' -or
            $text.IndexOf($expected.Replace('"','""'),[StringComparison]::OrdinalIgnoreCase) -lt 0) { throw 'reload-shim-owner' }
    } else {
        $exe = [IO.Path]::GetFileName($action.Execute)
        if ([IO.Path]::GetExtension($Script) -ieq '.py') {
            if ($exe -inotmatch '^pythonw?\.exe$' -or $action.Arguments -ine ('-u '+$expected) -or
                $action.WorkingDirectory -ine [IO.Path]::GetDirectoryName($Script)) { throw 'reload-task-owner' }
        } elseif ($exe -ine 'powershell.exe' -or ([string]$action.Arguments) -inotmatch ('(?:^|\s)-File '+[regex]::Escape($expected)+'\s*$')) { throw 'reload-task-owner' }
    }
}
function Write-SettingsReloadResult {
    param([string]$Path, $Result)
    $temporary = $Path + '.' + [guid]::NewGuid().ToString('N') + '.tmp'
    try { [IO.File]::WriteAllText($temporary,($Result | ConvertTo-Json -Compress),[Text.UTF8Encoding]::new($false)); Move-Item -LiteralPath $temporary -Destination $Path -Force }
    finally { if ([IO.File]::Exists($temporary)) { [IO.File]::Delete($temporary) } }
}
